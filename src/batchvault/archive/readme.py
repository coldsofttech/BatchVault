"""The ``BATCHVAULT-README.md`` written next to the manifest after ``pack``.

It tells someone who finds the archive years later, with no other context, how it
was made, how to get BatchVault and exactly how to restore it. It never contains
a password, key or token: it only says whether one is needed.

The first line is a marker. A file is only ever replaced when it carries the
marker, so a file of your own with the same name is never overwritten.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from functools import cache
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path
    from string import Template

    from batchvault.archive.manifest import Manifest

README_NAME = "BATCHVAULT-README.md"
MARKER = "<!-- Generated by BatchVault. Delete this line to keep your own edits. -->"

_SAFE = re.compile(r"^[\w.+@%/\\:=,-]+$")


@dataclass(frozen=True)
class ReadmeContext:
    """What the README says about a run. It deliberately has no secret fields."""

    engine: str
    format: str
    level: str  # "auto" or "0".."9"
    volume_size: int
    encrypted: bool
    signed: bool
    update: bool
    verified: bool
    delete_source: bool
    include: tuple[str, ...]
    exclude: tuple[str, ...]
    manifest_name: str
    created: str = ""


def _arg(value: str) -> str:
    """Quote ``value`` for a shell only when it needs it."""
    import shlex

    if value.startswith("-"):
        value = "./" + value
    return value if _SAFE.match(value) else shlex.quote(value)


def _yes(flag: bool) -> str:
    return "yes" if flag else "no"


def _patterns(values: tuple[str, ...]) -> str:
    return ", ".join(f"`{value}`" for value in values) if values else "none"


@cache
def _template(name: str) -> Template:
    """Load ``templates/<name>.md.tmpl`` shipped next to this module."""
    from importlib.resources import files
    from string import Template

    resource = files("batchvault.archive").joinpath("templates", f"{name}.md.tmpl")
    return Template(resource.read_text(encoding="utf-8"))


def _fragment(name: str, **values: str) -> str:
    """Render a small template without its final newline, to use inside a line."""
    return _template(name).substitute(values).rstrip("\n")


def _block(name: str, **values: str) -> str:
    """Render a template as its own paragraph, or nothing when ``name`` is empty."""
    return f"\n{_fragment(name, **values)}\n" if name else ""


def render_readme(context: ReadmeContext, manifest: Manifest) -> str:
    """Return the README text for ``manifest`` created with ``context``."""
    from datetime import UTC, datetime

    from batchvault import __version__
    from batchvault.core.options import format_size

    entries = list(manifest.entries.values())
    volumes = [volume for entry in entries for volume in entry.volumes]
    stored = sum(volume.size for volume in volumes)
    original = sum(entry.size for entry in entries)
    created = context.created or datetime.now(UTC).isoformat(timespec="seconds")

    needs_crypto = context.encrypted or context.signed
    sevenzip = context.engine == "7zip"
    version = __version__
    manifest_name = context.manifest_name

    one_volume = ""
    if entries and entries[0].volumes:
        first = _arg(entries[0].volumes[0].file)
        one_volume = _fragment("one-volume", first_volume=first) + "\n"

    return _template("readme").substitute(
        marker=MARKER,
        version=version,
        created=created,
        files=len(entries),
        volumes=len(volumes),
        original=format_size(original),
        stored=format_size(stored),
        manifest_name=manifest_name,
        manifest_arg=_arg(manifest_name),
        engine=context.engine,
        format=context.format,
        level=context.level,
        volume_size=format_size(context.volume_size),
        encrypted=_yes(context.encrypted),
        signed=_yes(context.signed),
        include=_patterns(context.include),
        exclude=_patterns(context.exclude),
        update=_yes(context.update),
        verified=_yes(context.verified),
        delete_source=_yes(context.delete_source),
        encrypted_note=_block("encrypted" if context.encrypted else ""),
        signed_note=_block(
            "signed" if context.signed else "", manifest_name=manifest_name
        ),
        extra="[crypto]" if needs_crypto else "",
        crypto=' with the "crypto" extra' if needs_crypto else "",
        docker_variant=_fragment("sevenzip-docker", version=version)
        if sevenzip
        else "",
        sevenzip_note=_block("sevenzip" if sevenzip else ""),
        restore_intro=_fragment(
            "restore-encrypted" if context.encrypted else "restore"
        ),
        sign_flag=" --public-key batchvault.pub" if context.signed else "",
        pass_flag=" --password-file password.txt" if context.encrypted else "",
        one_volume=one_volume,
    )


def _ours(path: Path) -> bool:
    """True if ``path`` is a file BatchVault wrote (its first line is the marker)."""
    try:
        with path.open("rb") as handle:
            first = handle.readline(len(MARKER) + 16)
    except OSError:
        return False
    return first.decode("utf-8", errors="replace").strip() == MARKER


def write_readme(path: Path, text: str) -> str | None:
    """Write the README atomically; return a warning instead of raising.

    Nothing is replaced unless it is a regular file with our marker, so a source
    file that happens to have this name (stored as a folder), a file of your own
    or a link is left alone.
    """
    import os
    import tempfile
    from pathlib import Path

    try:
        if path.is_symlink() or path.is_dir() or (path.exists() and not _ours(path)):
            return (
                f"{path.name} was not written: something else already uses that "
                "name. Use --no-readme to silence this."
            )

        path.parent.mkdir(parents=True, exist_ok=True)
        fd, name = tempfile.mkstemp(
            dir=path.parent, prefix=path.name + ".", suffix=".tmp"
        )
        temp = Path(name)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
            os.replace(temp, path)
        except BaseException:
            temp.unlink(missing_ok=True)
            raise
    except OSError as exc:
        return f"Could not write {path.name}: {exc}"
    return None
