"""The ``BATCHVAULT-README.md`` written next to the manifest after ``pack``.

It tells someone who finds the archive years later, with no other context, how it
was made, how to get BatchVault and exactly how to restore it. It never contains
a password, key or token: it only says whether one is needed.

The first line is a marker. A file is only ever replaced when it carries the
marker, so a file of your own with the same name is never overwritten.
"""

from __future__ import annotations

import os
import re
import shlex
import tempfile
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from batchvault import __version__
from batchvault.manifest import Manifest
from batchvault.options import format_size

README_NAME = "BATCHVAULT-README.md"
MARKER = "<!-- Generated by BatchVault. Delete this line to keep your own edits. -->"

_SAFE = re.compile(r"^[\w.+@%/\\:=,-]+$")


@dataclass(frozen=True)
class ReadmeContext:
    """What the README says about a run. It deliberately has no secret fields."""

    engine: str
    format: str
    level: str  # "auto" or "0".."9"
    volume_size: int
    encrypted: bool
    signed: bool
    update: bool
    verified: bool
    delete_source: bool
    include: tuple[str, ...]
    exclude: tuple[str, ...]
    manifest_name: str
    created: str = ""


def _arg(value: str) -> str:
    """Quote ``value`` for a shell only when it needs it."""
    if value.startswith("-"):
        value = "./" + value
    return value if _SAFE.match(value) else shlex.quote(value)


def _yes(flag: bool) -> str:
    return "yes" if flag else "no"


def _patterns(values: tuple[str, ...]) -> str:
    return ", ".join(f"`{value}`" for value in values) if values else "none"


def render_readme(context: ReadmeContext, manifest: Manifest) -> str:
    """Return the README text for ``manifest`` created with ``context``."""
    entries = list(manifest.entries.values())
    volumes = [volume for entry in entries for volume in entry.volumes]
    stored = sum(volume.size for volume in volumes)
    original = sum(entry.size for entry in entries)
    created = context.created or datetime.now(UTC).isoformat(timespec="seconds")

    manifest_arg = _arg(context.manifest_name)
    sign_flag = " --public-key batchvault.pub" if context.signed else ""
    pass_flag = " --password-file password.txt" if context.encrypted else ""
    crypto = ' with the "crypto" extra' if context.encrypted or context.signed else ""
    sevenzip = context.engine == "7zip"
    extra = "[crypto]" if context.encrypted or context.signed else ""

    lines = [
        MARKER,
        "# About this archive",
        "",
        "This folder is a [BatchVault](https://github.com/coldsofttech/BatchVault) "
        "archive: your files, compressed and split into volumes, with a manifest "
        "that records every volume and its checksum. This file explains how it "
        "was made and how to get the files back.",
        "",
        "## How this archive was made",
        "",
        f"- Created with BatchVault {__version__} on {created}",
        f"- Files: {len(entries)}, in {len(volumes)} volume(s)",
        f"- Size: {format_size(original)} original, {format_size(stored)} stored",
        f"- Manifest: `{context.manifest_name}` (lists every volume with its "
        "SHA-256 checksum)",
        "",
        "Settings of the run that wrote this file:",
        "",
        "| Setting | Value |",
        "|---|---|",
        f"| Engine | {context.engine} |",
        f"| Format | {context.format} |",
        f"| Compression level | {context.level} |",
        f"| Volume size | {format_size(context.volume_size)} |",
        f"| Encrypted | {_yes(context.encrypted)} |",
        f"| Signed manifest | {_yes(context.signed)} |",
        f"| Include patterns | {_patterns(context.include)} |",
        f"| Exclude patterns | {_patterns(context.exclude)} |",
        f"| Update mode (`--update`) | {_yes(context.update)} |",
        f"| Tested after creating | {_yes(context.verified)} |",
        f"| Originals deleted | {_yes(context.delete_source)} |",
        "",
        "Each file's own engine, format and level are recorded in the manifest; "
        "after an `--update` run the files may have been archived at different "
        "times and with different settings.",
    ]
    if context.encrypted:
        lines += [
            "",
            "**This archive is encrypted.** You need the password it was created "
            "with. It is not stored here or in the manifest, and without it the "
            "files cannot be restored.",
        ]
    if context.signed:
        lines += [
            "",
            f"**The manifest is signed** (`{context.manifest_name}.sig`). You need "
            "the matching public key to check the signature. It is not stored "
            "here; ask whoever made the archive.",
        ]

    lines += [
        "",
        "## Install BatchVault",
        "",
        "BatchVault needs Python 3.11.4 or later. To get exactly the version that "
        "made this archive:",
        "",
        "```",
        f'pip install "batchvault{extra}=={__version__}"',
        "```",
        "",
        f"or with pipx or uv{crypto}:",
        "",
        "```",
        f'pipx install "batchvault{extra}=={__version__}"',
        f'uv tool install "batchvault{extra}=={__version__}"',
        "```",
        "",
        "A newer version normally reads older archives too. Other ways to run it:",
        "",
        f"- Docker: `ghcr.io/coldsofttech/batchvault:{__version__}`"
        + (f" (use the `-7zip` variant: `:{__version__}-7zip`)" if sevenzip else ""),
        "- GitHub Action: `coldsofttech/BatchVault@v1`",
    ]
    if sevenzip:
        lines += [
            "",
            "These volumes are 7z archives: restoring them needs 7-Zip installed "
            "(pass its location with `--7z PATH` if it is not on your PATH).",
        ]

    lines += ["", "## Restore the files", ""]
    if context.encrypted:
        lines += [
            "Put the password in a file called `password.txt` (just the password) "
            "or set the `BATCHVAULT_PASSWORD` environment variable, then run "
            "this from this folder:",
        ]
    else:
        lines += ["Run this from this folder:"]
    lines += [
        "",
        "```",
        f"batchvault unpack {manifest_arg} -o restored{sign_flag}{pass_flag}",
        "```",
        "",
        "The files appear in `restored/`, in the same folders they came from. "
        "Every volume and every restored file is checked against its checksum "
        "before it is placed there.",
        "",
        "To check the archive without restoring it:",
        "",
        "```",
        f"batchvault verify {manifest_arg}{sign_flag}{pass_flag}",
        "```",
        "",
        "### Other ways to restore",
        "",
        "`unpack` and `verify` accept any of these in place of the manifest:",
        "",
        "- a folder: `batchvault unpack . -o restored`",
    ]
    if entries and entries[0].volumes:
        first = _arg(entries[0].volumes[0].file)
        lines.append(
            f"- one volume (any volume finds the rest): "
            f"`batchvault unpack {first} -o restored`"
        )
    lines += [
        "- a list of volumes or manifests, one path per line: "
        "`batchvault unpack volumes.txt -o restored`",
        "",
        "Add `--public-key` to check a signature and `--password-file` for an "
        "encrypted archive. Run `batchvault unpack --help` for everything else.",
        "",
    ]
    return "\n".join(lines)


def _ours(path: Path) -> bool:
    """True if ``path`` is a file BatchVault wrote (its first line is the marker)."""
    try:
        with path.open("rb") as handle:
            first = handle.readline(len(MARKER) + 16)
    except OSError:
        return False
    return first.decode("utf-8", errors="replace").strip() == MARKER


def write_readme(path: Path, text: str) -> str | None:
    """Write the README atomically; return a warning instead of raising.

    Nothing is replaced unless it is a regular file with our marker, so a source
    file that happens to have this name (stored as a folder), a file of your own
    or a link is left alone.
    """
    try:
        if path.is_symlink() or path.is_dir() or (path.exists() and not _ours(path)):
            return (
                f"{path.name} was not written: something else already uses that "
                "name. Use --no-readme to silence this."
            )

        path.parent.mkdir(parents=True, exist_ok=True)
        fd, name = tempfile.mkstemp(
            dir=path.parent, prefix=path.name + ".", suffix=".tmp"
        )
        temp = Path(name)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
            os.replace(temp, path)
        except BaseException:
            temp.unlink(missing_ok=True)
            raise
    except OSError as exc:
        return f"Could not write {path.name}: {exc}"
    return None
